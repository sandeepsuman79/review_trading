const { test } = require('node:test'), assert = require('node:assert/strict')
const fs = require('node:fs'), ts = require('typescript')
require.extensions['.ts'] = (m, f) => m._compile(ts.transpileModule(fs.readFileSync(f, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, f)
const { createIntrabarContextStore } = require('../src/analysis/intrabarContext.ts')
const now = Date.parse('2026-10-16T12:00:00+05:30')
const tick = (time, ltp = 100, values = {}) => ({ mode: 1, exchangeType: 1, token: '99926000', timestamp: time, ltp, ...values })

test('index quote context needs two real timestamps spanning five seconds and never infers volume from sample count', () => {
  const store = createIntrabarContextStore(), identity = tick(now)
  assert.equal(store.readIntrabarContext(identity, now).state, 'WARMING_UP')
  assert(store.recordIntrabarTick(identity, now)); assert(store.recordIntrabarTick(tick(now + 4000, 101), now + 4000))
  assert.equal(store.readIntrabarContext(identity, now + 4000).priceChange, undefined)
  store.recordIntrabarTick(tick(now + 5000, 102), now + 5000)
  const result = store.readIntrabarContext('1:99926000', now + 5000)
  assert.equal(result.state, 'OBSERVED'); assert.equal(result.priceChange, 2); assert.equal(result.priceChangePercent, 2)
  assert.equal(result.sampleCount, 3); assert.equal(result.spanMs, 5000); assert.equal(result.cumulativeVolumeDelta, undefined)
})
test('MCX cumulative volume delta uses actual nondecreasing counters and excludes missing or reset counters', () => {
  const store = createIntrabarContextStore(), values = { mode: 2, exchangeType: 5, token: 'MCX1', volume: 1000 }
  store.recordIntrabarTick(tick(now, 100, values), now)
  store.recordIntrabarTick(tick(now + 5000, 101, { ...values, volume: 1040 }), now + 5000)
  assert.equal(store.readIntrabarContext('5:MCX1', now + 5000).cumulativeVolumeDelta, 40)
  store.recordIntrabarTick(tick(now + 10000, 99, { ...values, volume: 5 }), now + 10000)
  assert.equal(store.readIntrabarContext('5:MCX1', now + 10000).cumulativeVolumeDelta, undefined)
  store.recordIntrabarTick(tick(now + 35000, 98, { ...values, volume: 10 }), now + 35000)
  store.recordIntrabarTick(tick(now + 40000, 99, { ...values, volume: 20 }), now + 40000)
  assert.equal(store.readIntrabarContext('5:MCX1', now + 40000).cumulativeVolumeDelta, 15)
  store.recordIntrabarTick(tick(now + 45000, 100, { ...values, volume: undefined }), now + 45000)
  assert.equal(store.readIntrabarContext('5:MCX1', now + 45000).cumulativeVolumeDelta, undefined)
})
test('new IST sessions and gaps cannot fabricate an overnight or disconnected move', () => {
  const store = createIntrabarContextStore(), midnight = Date.parse('2026-10-17T00:00:00+05:30')
  store.recordIntrabarTick(tick(midnight - 4000, 100, { volume: 500 }), midnight - 4000)
  store.recordIntrabarTick(tick(midnight + 1000, 90, { volume: 1 }), midnight + 1000)
  const fresh = store.readIntrabarContext('1:99926000', midnight + 1000)
  assert.equal(fresh.state, 'WARMING_UP'); assert.equal(fresh.sampleCount, 1); assert.equal(fresh.priceChange, undefined)
  store.recordIntrabarTick(tick(midnight + 40000, 95, { volume: 10 }), midnight + 40000)
  assert.equal(store.readIntrabarContext('1:99926000', midnight + 40000).state, 'WARMING_UP')
  assert.equal(store.readIntrabarContext('1:99926000', midnight + 70001).state, 'STALE')
})
test('stale, future, duplicate, out-of-order and invalid quotes do not replace monotonic actual observations', () => {
  const store = createIntrabarContextStore()
  assert(!store.recordIntrabarTick(tick(now - 30001), now)); assert(!store.recordIntrabarTick(tick(now + 1001), now))
  for (const patch of [{ timestamp: NaN }, { timestamp: -1 }, { ltp: 0 }, { ltp: NaN }, { token: '' }, { exchangeType: 0 }]) assert(!store.recordIntrabarTick(tick(now, 100, patch), now))
  assert(!store.recordIntrabarTick(tick(8640000000000000), 8640000000000000))
  assert(store.recordIntrabarTick(tick(now / 1000), now), 'epoch seconds use actual timestamp normalization')
  assert(!store.recordIntrabarTick(tick(now, 200), now)); assert(!store.recordIntrabarTick(tick(now - 1, 200), now))
  assert(store.recordIntrabarTick(tick(now + 5000, 101), now + 5000))
  assert.equal(store.readIntrabarContext('1:99926000', now + 5000).priceChange, 1)
  assert.equal(store.readIntrabarContext('1:99926000', now - 2000).state, 'STALE')
})
test('exact exchange/token identities isolate contracts, and key/sample memory remains bounded', () => {
  const store = createIntrabarContextStore()
  for (const [exchangeType, token, offset] of [[1, 'same', 0], [5, 'same', 10], [5, 'rollover', 20]]) {
    store.recordIntrabarTick(tick(now, 100 + offset, { exchangeType, token }), now)
    store.recordIntrabarTick(tick(now + 5000, 101 + offset, { exchangeType, token }), now + 5000)
  }
  assert.equal(store.readIntrabarContext('1:same', now + 5000).priceChange, 1)
  assert.equal(store.readIntrabarContext('5:same', now + 5000).priceChange, 1)
  assert.equal(store.readIntrabarContext('5:rollover', now + 5000).priceChange, 1)
  assert.equal(store.readIntrabarContext('3:same', now + 5000).state, 'WARMING_UP')
  for (let key = 0; key < 40; key++) for (let sample = 0; sample < 250; sample++) store.recordIntrabarTick(tick(now + sample * 25, 100 + sample, { token: `key${key}` }), now + sample * 25)
  const stats = store.stats(); assert.equal(stats.keys, 32); assert(stats.samples <= 32 * 180)
  assert.equal(store.readIntrabarContext('1:key0', now + 6250).sampleCount, 0)
  const dense = store.readIntrabarContext('1:key39', now + 6250)
  assert.equal(dense.state, 'OBSERVED'); assert.equal(dense.sampleCount, 180); assert.equal(dense.priceChange, 249)
})
test('dense-sample compaction cannot erase an observed volume counter reset', () => {
  const store = createIntrabarContextStore()
  store.recordIntrabarTick(tick(now, 100, { volume: 100 }), now)
  for (let sample = 1; sample <= 250; sample++) store.recordIntrabarTick(tick(now + sample * 25, 100 + sample, { volume: sample }), now + sample * 25)
  const result = store.readIntrabarContext('1:99926000', now + 6250)
  assert.equal(result.state, 'OBSERVED'); assert.equal(result.cumulativeVolumeDelta, undefined)
})
